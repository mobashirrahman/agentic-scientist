"""Build ATLAS.md: facts about every ALLOWED released stage (held-out evaluation targets are excluded)."""
import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT))
from src.data import load_stage  # noqa: E402

DENY = json.loads((ROOT / 'agentic_scientist/config.json').read_text())['holdout_forbidden']
FILES = ['T1/E8.5_RNA.h5ad', 'T1/E9.5_RNA.h5ad', 'T1/E10.5_RNA.h5ad'] + \
    [f'T2/{s}.h5ad' for s in ('E6.75', 'E7.25', 'E8.0', 'E8.25_late', 'E8.5', 'E8.75', 'E9.5')] + \
    ['T3/E8.75_gata4_ko_1.h5ad', 'T3/E8.75_gata4_ko_2.h5ad']
out = ['# Data atlas (allowed stages only)\n',
       'Generated by build_atlas.py. Expression is log1p(CP10k). rms = root-mean-square radius of spatial_3D about its centroid.\n']
prev = {}
for f in FILES:
    assert not any(d.lower() in f.lower() for d in DENY), f
    a = load_stage(f)
    X = a.X
    nnz = X.getnnz(1) if hasattr(X, 'getnnz') else (np.asarray(X) > 0).sum(1)
    out.append(f'\n## {f}\ncells {a.n_obs}, genes {a.n_vars}, median genes/cell {int(np.median(nnz))}, obs: {", ".join(a.obs.columns[:12])}')
    if 'spatial_3D' in a.obsm:
        C = np.asarray(a.obsm['spatial_3D'], float)
        Cc = C - C.mean(0)
        out.append(f'spatial rms {np.sqrt((Cc ** 2).sum(1).mean()):.1f}; extent min {C.min(0).round(0).tolist()} max {C.max(0).round(0).tolist()}')
    if 'celltype' in a.obs:
        vc = a.obs['celltype'].astype(str).value_counts(normalize=True)
        out.append(f'{len(vc)} cell types: ' + ', '.join(f'{k} {v:.3f}' for k, v in vc.items()))
        group = f.split('/')[0]
        if group in prev:
            new = sorted(set(vc.index) - prev[group])
            gone = sorted(prev[group] - set(vc.index))
            out.append(f'vs previous {group} stage: new types {new or "none"}; disappeared {gone or "none"}')
        prev[group] = set(vc.index)
    del a
for f in sorted((ROOT / 'data/external/qiu2024').glob('*.h5ad')):
    import anndata as ad
    a = ad.read_h5ad(f, backed='r')
    out.append(f'\n## external/qiu2024/{f.name}\ncells {a.n_obs}, genes {a.n_vars}, obs: {", ".join(a.obs.columns[:10])}')
Path(__file__).with_name('ATLAS.md').write_text('\n'.join(out) + '\n')
print('ok', len('\n'.join(out)))
